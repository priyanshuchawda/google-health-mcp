import { readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

const output = await build({
  entryPoints: ["src/ui/dashboard-app.ts"],
  bundle: true,
  minify: true,
  platform: "browser",
  format: "iife",
  target: ["es2022"],
  write: false,
  outfile: "dashboard-app.js",
  logLevel: "warning",
});
const javascript = output.outputFiles.find((file) => file.path.endsWith(".js"));
const css = output.outputFiles.find((file) => file.path.endsWith(".css"));
if (!javascript) throw new Error("Dashboard JavaScript bundle was not built.");
const shell = await readFile("src/ui/dashboard-shell.html", "utf8");
const html = shell
  .replace("__APP_CSS__", (css?.text ?? "").replaceAll("</style", "<\\/style"))
  .replace("__APP_JS__", javascript.text.replaceAll("</script", "<\\/script"));
const moduleSource = `// Generated by scripts/build-dashboard.mjs. Do not edit by hand.\nexport const HEALTH_DASHBOARD_HTML = ${JSON.stringify(html)};\n`;
await writeFile("src/ui/dashboard-resource.ts", moduleSource, "utf8");
